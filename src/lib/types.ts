/**
 * Core data models for Product Opportunity Finder.
 *
 * Every record is user-entered. Nothing in this app generates or estimates
 * market data — scores are derived only from ratings the user assigns and
 * explains. Field names are chosen to map 1:1 onto future Supabase tables
 * (camelCase here, snake_case columns via the adapter).
 */

export interface BaseRecord {
  id: string;
  createdAt: string; // ISO timestamp
  updatedAt: string; // ISO timestamp
}

/* ------------------------------------------------------------------ Niches */

export const NICHE_STATUSES = ["exploring", "promising", "paused", "rejected"] as const;
export type NicheStatus = (typeof NICHE_STATUSES)[number];

export interface Observation {
  id: string;
  note: string;
  sourceUrl: string;
  date: string; // YYYY-MM-DD
}

export interface Niche extends BaseRecord {
  name: string;
  description: string;
  status: NicheStatus;
  subNiches: string[];
  audiences: string[];
  observations: Observation[];
}

/* ---------------------------------------------------------------- Problems */

export type Rating = 1 | 2 | 3 | 4 | 5;

export interface Problem extends BaseRecord {
  title: string;
  nicheId: string | null;
  audience: string;
  description: string;
  pain: Rating;
  frequency: Rating;
  willingnessToPay: Rating;
  evidence: string;
  sourceUrls: string[];
}

/* ------------------------------------------------------------- Competitors */

export const PRODUCT_FORMATS = [
  "Printable PDF",
  "Digital planner",
  "Notion template",
  "Spreadsheet template",
  "Canva template",
  "SVG / clipart bundle",
  "Ebook / guide",
  "Workbook / course",
  "Other",
] as const;
export type ProductFormat = (typeof PRODUCT_FORMATS)[number];

export interface Competitor extends BaseRecord {
  competitorName: string;
  productName: string;
  price: number | null; // as observed on the listing; null = not recorded
  productType: ProductFormat;
  nicheId: string | null;
  strengths: string;
  weaknesses: string;
  differentiation: string;
  evidenceUrl: string;
}

/* ---------------------------------------------------------------- Keywords */

export const SEARCH_INTENTS = ["informational", "commercial", "transactional", "navigational"] as const;
export type SearchIntent = (typeof SEARCH_INTENTS)[number];

export const COMPETITION_LEVELS = ["low", "medium", "high", "unknown"] as const;
export type CompetitionLevel = (typeof COMPETITION_LEVELS)[number];

export interface Keyword extends BaseRecord {
  keyword: string;
  nicheId: string | null;
  intent: SearchIntent;
  competition: CompetitionLevel;
  source: string; // e.g. "Etsy search autocomplete", "eRank", "Google Trends"
  notes: string;
}

/* ----------------------------------------------------- Opportunity scoring */

export const CRITERIA = [
  "demand",
  "pain",
  "competition",
  "willingnessToPay",
  "feasibility",
] as const;
export type CriterionKey = (typeof CRITERIA)[number];

export interface CriterionAssessment {
  /** 0–5, or null when not yet assessed. */
  rating: number | null;
  reasoning: string;
}

export interface Opportunity extends BaseRecord {
  title: string;
  nicheId: string | null;
  problemId: string | null;
  criteria: Record<CriterionKey, CriterionAssessment>;
  notes: string;
}

/* ----------------------------------------------------------- Product ideas */

export const DIFFICULTIES = ["low", "medium", "high"] as const;
export type Difficulty = (typeof DIFFICULTIES)[number];

export const VALIDATION_STATUSES = [
  "idea",
  "researching",
  "validating",
  "validated",
  "launched",
  "rejected",
] as const;
export type ValidationStatus = (typeof VALIDATION_STATUSES)[number];

export interface ProductIdea extends BaseRecord {
  name: string;
  problemId: string | null;
  problemSolved: string;
  targetCustomer: string;
  solution: string;
  usp: string;
  format: ProductFormat;
  difficulty: Difficulty;
  opportunityId: string | null; // score is read from the linked opportunity
  validationStatus: ValidationStatus;
}

/* ---------------------------------------------------------------- Database */

export interface Database {
  niches: Niche[];
  problems: Problem[];
  competitors: Competitor[];
  keywords: Keyword[];
  opportunities: Opportunity[];
  ideas: ProductIdea[];
}

export type CollectionName = keyof Database;
export type EntityOf<K extends CollectionName> = Database[K][number];

/** Input shape for create: system fields are generated by the store. */
export type NewRecord<T extends BaseRecord> = Omit<T, "id" | "createdAt" | "updatedAt">;

export const COLLECTIONS: CollectionName[] = [
  "niches",
  "problems",
  "competitors",
  "keywords",
  "opportunities",
  "ideas",
];

export const emptyDatabase = (): Database => ({
  niches: [],
  problems: [],
  competitors: [],
  keywords: [],
  opportunities: [],
  ideas: [],
});
